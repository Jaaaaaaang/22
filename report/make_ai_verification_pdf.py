def P(t, st=B): return Paragraph(t, st)

def table(rows, widths, head=True, key=True, fs=B):
    data = []
    for i, r in enumerate(rows):
        row = []
        for j, c in enumerate(r):
            if head and i == 0: row.append(P(c, HD))
            elif key and j == 0: row.append(P(c, K))
            else: row.append(P(c, fs))
        data.append(row)
    t = Table(data, colWidths=widths, repeatRows=1 if head else 0)
    st = [("GRID", (0, 0), (-1, -1), 0.4, LINE), ("VALIGN", (0, 0), (-1, -1), "TOP"),
          ("LEFTPADDING", (0, 0), (-1, -1), 3), ("RIGHTPADDING", (0, 0), (-1, -1), 3),
          ("TOPPADDING", (0, 0), (-1, -1), 2), ("BOTTOMPADDING", (0, 0), (-1, -1), 2)]
    if head: st.append(("BACKGROUND", (0, 0), (-1, 0), NAVY))
    if key: st.append(("BACKGROUND", (0, 1 if head else 0), (0, -1), GRAY))
    t.setStyle(TableStyle(st)); return t

